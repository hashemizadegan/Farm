/**
 * Builds `clients/unity-starter/Samples/claim-payloads.sample.json` from the **live** output of the cycle
 * pipeline: the multi-party simulation scenario of PR #73 is run end to end, and its frozen artifact is
 * served through the claim lookup. The C# tests verify these payloads with `VerifyClaimLeafProof`.
 * `claim-lookup.sample.test.ts` regenerates the file and requires the committed copy to match exactly.
 */
import { SHA256_RFC9162_HASHER } from "./claim-tree";
import { type ClaimLookupResult, createClaimLookup } from "./claim-lookup";
import { calculateSimulationCycle } from "./pipeline";
import { input } from "./pipeline.scenario.test-support";

export async function claimPayloadSample() {
  const { artifact, artifactSha256 } = await calculateSimulationCycle(await input());
  const lookup = await createClaimLookup(artifact, artifactSha256, SHA256_RFC9162_HASHER);
  const lookups: { query: { partyId: string } | { payoutAddress: string }; result: ClaimLookupResult["status"]; reason?: string; deferredReason?: string }[] = [];
  const record = (query: { partyId: string } | { payoutAddress: string }, r: ClaimLookupResult) =>
    lookups.push({ query, result: r.status, ...(r.status === "no_leaf" ? { reason: r.reason, ...(r.reason === "deferred" ? { deferredReason: r.deferredReason } : {}) } : {}) });
  for (const id of ["party-a", "party-b", "party-c", "party-d", "token-account-x", "nobody"]) record({ partyId: id }, lookup.byPartyId(id));
  record({ payoutAddress: "So11111111111111111111111111111111111111112" }, lookup.byPayoutAddress("So11111111111111111111111111111111111111112"));
  return {
    description:
      "Claim payloads (metafarm-yield-claim/1) served by packages/domain/src/yield/claim-lookup.ts from the frozen artifact of the PR #73 multi-party simulation cycle, generated by claim-lookup.sample.test-support.ts. Verify each claim against publishedTree, never against the root or size inside the claim. Simulation only.",
    artifactSha256,
    publishedTree: lookup.published,
    claims: lookup.all(),
    lookups,
  };
}

/** The file's exact text: two-space JSON with a trailing newline. */
export async function claimPayloadSampleText(): Promise<string> {
  return `${JSON.stringify(await claimPayloadSample(), null, 2)}\n`;
}
