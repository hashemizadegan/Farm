/**
 * Builds `clients/unity-starter/Samples/claim-payloads.tiny-holders.sample.json`: a seeded simulation cycle
 * whose ownership includes many tiny holders (extreme u64 profile), run end to end through the pipeline with
 * dust threshold 0. Under the zero-allocation policy their 0 amounts are deferred (`zero_amount`), never
 * claims. The file carries the shares, the settlement amount and the plan's entries, so the C# tests can
 * recompute the largest-remainder allocation and the state rule independently and verify every claim.
 * `zero-allocation.test.ts` regenerates it and requires the committed copy to match exactly.
 */
import { SHA256_RFC9162_HASHER } from "./claim-tree";
import { createClaimLookup } from "./claim-lookup";
import { SIMULATION_DISTRIBUTION_POLICY } from "./distribution";
import { MockOwnershipAdapter, type OwnershipSnapshotRequest, loadVerifiedOwnershipSnapshot } from "./ownership-source";
import { calculateSimulationCycle } from "./pipeline";
import { input } from "./pipeline.scenario.test-support";

export const TINY_REQUEST: OwnershipSnapshotRequest = { assetId: "bb".repeat(32), networkId: "simulation", reference: { kind: "slot", value: 260_000_000n }, verifiedAt: "2026-10-01T09:00:00Z" };
export const TINY_MOCK = new MockOwnershipAdapter({ seed: 0x7171n, holders: 48, profile: "extreme", withheldEvery: 11, unattributed: 2, observedAt: "2026-09-30T23:59:59Z" });

/** Runs the tiny-holders cycle (dust threshold 0). */
export async function tinyHoldersCycle() {
  const ownership = await loadVerifiedOwnershipSnapshot(TINY_MOCK, TINY_REQUEST);
  const base = await input();
  const result = await calculateSimulationCycle({ ...base, ownership, distributionPolicy: { ...SIMULATION_DISTRIBUTION_POLICY, dustThreshold: 0n, missingPayoutWallet: "withhold" } });
  return { ownership, ...result };
}

export async function tinyHoldersSample() {
  const { artifact, artifactSha256 } = await tinyHoldersCycle();
  const lookup = await createClaimLookup(artifact, artifactSha256, SHA256_RFC9162_HASHER);
  const plan = artifact.distribution.plan;
  const s = (v: bigint) => v.toString();
  return {
    description:
      "A seeded simulation cycle with many tiny holders (MockOwnershipAdapter seed 0x7171, 48 holders, extreme u64 shares, every 11th withheld, 2 unattributed), run through the pipeline with dust threshold 0. Zero-allocation policy: a party whose amount is 0 is deferred with deferredReason zero_amount and never gets a claim. Shares are listed with their split keys (UTF-8 'p:' + party id or 'u:' + holder key; equal fractions are broken by ascending key bytes) so the allocation can be recomputed. Generated by zero-allocation.sample.test-support.ts. Simulation only.",
    settlement: { amount: s(artifact.calculation.settlementAmount), dustThreshold: s(plan.policy.dustThreshold), remainder: plan.policy.remainder },
    shares: plan.entries.map((e) => ({ key: e.kind === "party" ? `p:${e.partyId}` : `u:${e.holderKey}`, kind: e.kind, hasPayoutWallet: e.payoutWallet !== null, weight: s(e.weight) })),
    entries: plan.entries.map((e) => ({ key: e.kind === "party" ? `p:${e.partyId}` : `u:${e.holderKey}`, state: e.state, deferredReason: e.deferredReason, allocated: s(e.allocated), amount: s(e.amount) })),
    totals: Object.fromEntries(Object.entries(artifact.totals).map(([k, v]) => [k, s(v)])),
    artifactSha256,
    publishedTree: lookup.published,
    claims: lookup.all(),
  };
}

/** The file's exact text: two-space JSON with a trailing newline. */
export async function tinyHoldersSampleText(): Promise<string> {
  return `${JSON.stringify(await tinyHoldersSample(), null, 2)}\n`;
}
