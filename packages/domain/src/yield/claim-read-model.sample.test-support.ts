/**
 * Builds `clients/unity-starter/Samples/claim-readmodel.sample.json`: the 4,096-holder cycle of the #78
 * large-tree sample, projected into a read model, persisted as a byte image, loaded back, and queried for the
 * same 64 seeded holders. The C# tests verify these claims and require them to equal the large-tree sample's
 * claims for the same parties, byte for byte.
 */
import { SHA256_RFC9162_HASHER } from "./claim-tree";
import { InMemoryClaimReadModelStore, decodeReadModelImage, encodeReadModelImage, openClaimReadModel, projectClaimReadModel } from "./claim-read-model";
import { LARGE_SAMPLE, largeHolderCycle, pickParties } from "./large-holder.test-support";

let memo: ReturnType<typeof build> | undefined;

async function build() {
  const r = await largeHolderCycle(LARGE_SAMPLE.holders, LARGE_SAMPLE.seed);
  const store = new InMemoryClaimReadModelStore();
  const header = await projectClaimReadModel(r.artifact, r.artifactSha256, SHA256_RFC9162_HASHER, store);
  const image = await encodeReadModelImage(store);
  return { ...r, store, header, image };
}

/** The 4,096-holder sample cycle and its read model (built once per process). */
export const sampleReadModel = () => (memo ??= build());

export async function claimReadModelSample() {
  const { ownership, header, image } = await sampleReadModel();
  const loaded = await decodeReadModelImage(image.bytes, image.sha256);
  const model = await openClaimReadModel(loaded, { cycleId: header.cycleId, cycleVersion: header.cycleVersion, artifactSha256: header.artifactSha256 }, SHA256_RFC9162_HASHER);
  const picked = pickParties(
    ownership.entries.map((e) => e.partyId),
    LARGE_SAMPLE.picks,
    LARGE_SAMPLE.pickSeed,
  );
  const claims = [];
  const reads: { partyId: string; gets: number; bytesRead: number }[] = [];
  for (const partyId of picked) {
    const before = { ...loaded.stats };
    const result = await model.byPartyId(partyId);
    if (result.status !== "claim") continue;
    claims.push(result.claim);
    reads.push({ partyId, gets: loaded.stats.gets - before.gets, bytesRead: loaded.stats.bytesRead - before.bytesRead });
  }
  return {
    description:
      "Claims served by the claim read model (claim-read-model.ts) for the 64 seeded holders of the #78 large-tree sample: the 4,096-holder cycle projected into records, persisted as a byte image (imageSha256), loaded back and queried one holder at a time. Each claim must equal the large-tree sample's claim for the same party and verify against header.published. reads: store reads per lookup (2 + path length). Generated by claim-read-model.sample.test-support.ts. Simulation only.",
    imageSha256: image.sha256,
    imageBytes: image.bytes.length,
    records: loaded.size,
    header: model.header,
    reads,
    claims,
  };
}

export async function claimReadModelSampleText(): Promise<string> {
  return `${JSON.stringify(await claimReadModelSample(), null, 2)}\n`;
}
