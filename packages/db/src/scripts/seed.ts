/**
 * Development seed. Creates a demo tenant, a dev user and a small illustrative
 * asset catalogue. It deliberately creates NO observations, imagery, sensor
 * readings or financial figures: those must come from real users or real
 * integrations.
 *
 * Refuses to run when APP_ENV is staging or production.
 */
import { createPool } from "../pool";
import { withSystem } from "../tenant";
import { createTenantWithOwner, upsertUserBySubject } from "../repositories/identity";

if (process.env.APP_ENV === "staging" || process.env.APP_ENV === "production") {
  console.error("seed is development-only");
  process.exit(1);
}
const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is required");
  process.exit(1);
}

const pool = createPool({ connectionString: url, max: 2 });

const CATALOG = [
  { kind: "plant", name: "Generic row crop (procedural)", procedural: { shape: "cone", heightM: 0.9, radiusM: 0.25, color: "#4f8a3a" } },
  { kind: "plant", name: "Generic shrub (procedural)", procedural: { shape: "sphere", heightM: 1.2, radiusM: 0.6, color: "#3f7a34" } },
  { kind: "plant", name: "Generic tree (procedural)", procedural: { shape: "tree", heightM: 4, radiusM: 1.6, color: "#2f6a2c" } },
  { kind: "equipment", name: "Tractor placeholder (procedural)", procedural: { shape: "box", widthM: 2.4, heightM: 2.8, depthM: 4.2, color: "#b5452f" } },
  { kind: "structure", name: "Storage shed placeholder (procedural)", procedural: { shape: "box", widthM: 6, heightM: 3.5, depthM: 8, color: "#8a7a63" } },
  { kind: "structure", name: "Sensor post placeholder (procedural)", procedural: { shape: "cylinder", heightM: 1.5, radiusM: 0.05, color: "#cccccc" } },
] as const;

try {
  await withSystem(pool, async (tx) => {
    const existing = await tx.query(`SELECT id FROM tenants WHERE slug = 'demo'`);
    if ((existing.rowCount ?? 0) > 0) {
      console.log("[seed] demo tenant already exists; skipping");
      return;
    }
    const user = await upsertUserBySubject(pool, {
      issuer: "dev",
      subject: "dev-user",
      email: "dev@example.invalid",
      name: "Dev User",
    });
    const tenantId = await createTenantWithOwner(tx, { slug: "demo", name: "Demo Tenant", ownerUserId: user.id });

    const second = await upsertUserBySubject(pool, { issuer: "dev", subject: "dev-other", name: "Other Tenant User" });
    await createTenantWithOwner(tx, { slug: "other", name: "Other Tenant", ownerUserId: second.id });

    for (const a of CATALOG) {
      await tx.query(
        `INSERT INTO asset_catalog (tenant_id, kind, name, procedural, license)
         VALUES (NULL, $1, $2, $3::jsonb, 'Procedural geometry generated by this application')`,
        [a.kind, a.name, JSON.stringify(a.procedural)],
      );
    }
    console.log(`[seed] created tenant demo (${tenantId}), user dev-user, tenant other, ${CATALOG.length} catalog entries`);
  });
} finally {
  await pool.end();
}
