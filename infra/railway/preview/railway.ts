/**
 * Railway Infrastructure as Code for the ISOLATED YIELD PREVIEW (a separate Railway project, never the live one).
 *
 *   railway link                      # choose the preview project (name starts with "metafarm-yield-preview")
 *   railway config plan  --file infra/railway/preview/railway.ts
 *   railway config apply --file infra/railway/preview/railway.ts   # only after the approvals in
 *                                                                   # docs/delivery/yield-security-review-package-*.md §B
 *
 * The live project is described by .railway/railway.ts and is never touched by this file: the guard below refuses
 * to render anything unless the linked project is a preview project, so a mis-linked `plan`/`apply` fails before
 * it can compute a change. Runbook: docs/preview-runbook.md. Variable names and placeholders: .env.preview.example.
 *
 * What runs here (simulation only):
 * - postgres (PostGIS) and redis: new, private, preview-only;
 * - api: APP_ENV=development with dev sign-in, the yield workflow and simulation claim intents on, the access gate
 *   on (the API refuses to start on the platform with a development configuration and the gate off);
 * - web: the /yield staff pages, behind HTTP Basic (PREVIEW_ACCESS_PASSWORD), health check /healthz;
 * - seed-runner: one-off; seeds the demo workspace and simulation cycles, then exits (Dockerfile target
 *   app-seed-runner; refuses non-fresh databases).
 * Not deployed: worker and scheduler (no jobs needed for the operator pages), any bucket (memory storage), and every
 * chain, signer, RPC, DAS, TRON or mainnet variable. Holder-facing switches stay off.
 */
import { defineRailway, github, image, preserve, project, redis, service, volume } from "railway/iac";

const REPO = "hashemizadegan/Farm";
/** The branch the preview deploys: the preview line with its add-ons merged (#99 + #100 + #101 + this change). */
const PREVIEW_BRANCH = "preview/yield-simulation";
/** The live project. This file must never render against it. */
const LIVE_PROJECT_ID = "79dfa6d8-e825-408d-b08f-7fba31dd7954";
const LIVE_PROJECT_NAME = "melodious-liberation";
const PREVIEW_PROJECT_PREFIX = "metafarm-yield-preview";

export default defineRailway((ctx) => {
  if (ctx.projectId === LIVE_PROJECT_ID || ctx.projectName === LIVE_PROJECT_NAME || !ctx.projectName?.startsWith(PREVIEW_PROJECT_PREFIX)) {
    throw new Error(
      `refusing to render the yield preview for project "${ctx.projectName}" (${ctx.projectId}): link a separate project whose name starts with "${PREVIEW_PROJECT_PREFIX}"`,
    );
  }

  const src = () => github(REPO, { branch: PREVIEW_BRANCH, rootDirectory: "/" });

  const pgData = volume("postgres-data", { sizeMB: 5_120 });
  const db = service("postgres", {
    source: image("postgis/postgis:16-3.4"),
    volumeMounts: { "/var/lib/postgresql/data": pgData },
    env: {
      POSTGRES_USER: "metafarm",
      POSTGRES_DB: "metafarm",
      POSTGRES_PASSWORD: preserve(), // generated by the operator in the preview project; never committed
      PGDATA: "/var/lib/postgresql/data/pgdata",
    },
  });
  const cache = redis("redis");
  const dbUrl = "postgres://metafarm:${{postgres.POSTGRES_PASSWORD}}@postgres.railway.internal:5432/metafarm";

  /** Shared by the API and the seed runner (the yield seed builds the API in-process). */
  const previewApiEnv = {
    APP_ENV: "development",
    LOG_LEVEL: "info",
    HOST: "::",
    DATABASE_URL: dbUrl,
    REDIS_URL: cache.env.REDIS_URL,
    QUEUE_PREFIX: "preview",
    STORAGE_DRIVER: "memory",
    AUTH_PROVIDER: "dev",
    DEV_AUTH_SECRET: preserve(), // generated by the operator (>= 32 chars); also used offline to mint dev tokens
    PREVIEW_ACCESS_GATE: "true",
    YIELD_WORKFLOW_ENABLED: "true",
    YIELD_CLAIM_INTENTS_ENABLED: "true",
  };

  const api = service("api", {
    source: src(),
    preDeploy: "node dist/migrate.js", // migrations 0001–0029 on the preview database only
    healthcheck: "/readyz",
    healthcheckTimeout: 60,
    replicas: 1,
    env: {
      APP: "api",
      ...previewApiEnv,
      CORS_ORIGINS: preserve(), // the preview web origin, e.g. https://web-<id>.up.railway.app
      SHUTDOWN_GRACE_MS: "15000",
    },
  });

  const web = service("web", {
    source: src(),
    healthcheck: "/healthz", // the only path the access gate serves without credentials
    replicas: 1,
    env: {
      APP: "web",
      APP_ENV: "development",
      NEXT_PUBLIC_API_URL: preserve(), // the preview API's public URL (inlined at build time)
      NEXT_PUBLIC_YIELD_PAGES_ENABLED: "true",
      PREVIEW_ACCESS_GATE: "true",
      PREVIEW_ACCESS_PASSWORD: preserve(), // generated by the operator (>= 24 chars); shared out of band
    },
  });

  // One-off: deploys once, seeds, exits 0. Set its restart policy to "Never" in the service settings (not part of
  // this DSL). A redeploy is harmless: the seeds are idempotent and the runner refuses any non-fresh database.
  const seedRunner = service("seed-runner", {
    source: src(),
    env: {
      APP: "seed-runner",
      ...previewApiEnv,
    },
  });

  return project("metafarm-yield-preview", { resources: [db, pgData, cache, api, web, seedRunner] });
});
